/** 按日期倒序；同日则按 id 升序，保证每次渲染顺序稳定 */
function byDateDesc(a: Article, b: Article): number {
  const d = b.date.localeCompare(a.date);
  return d !== 0 ? d : a.id.localeCompare(b.id);
}

