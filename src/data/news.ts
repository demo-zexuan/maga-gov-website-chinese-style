/**
 * 要闻动态数据源
 *
 * I. 本文件是什么
 *
 * 1. 全站「要闻动态」栏目（头条新闻 / 总统活动 / 部委动态 / 地方传真）的唯一数据源。
 * 2. 共收录 44 篇虚构新闻稿，日期区间为 2026-03-01 至 2026-04-12，统一按日期倒序排列。
 * 3. 首页要闻区、栏目列表页、新闻详情页与全站搜索结果共用本文件。
 *
 * II. 写作约定
 *
 * 1. 语气一律采用标准的公文与新闻通稿语气，荒谬只允许藏在具体细节、数字与时限里。
 * 2. 全文不使用感叹号、不使用 emoji、不使用网络流行语，判断句一律改为"拟""将""正在"。
 * 3. 文稿中的机构、人物、文号、统计数字全部为虚构，属讽刺文学创作，与任何真实主体无关。
 *
 * III. 数据结构
 *
 * 1. 每条 Article 的 body 为 3 至 8 段完整正文，均可独立阅读，不使用占位文本。
 * 2. category 取值见 NEWS_CATEGORIES：top / president / dept / local。
 * 3. docNo 只出现在"以文件形式印发"的稿件上，用于区分通稿与红头文件。
 *
 * @module data/news
 * @author zexuan.peng <pengzexuan2001@gmail.com>
 * @created 2026-09-30
 */
import type { Article } from './types';

/* ================= 栏目定义 ================= */

/** 要闻动态的四个子栏目 */
export type NewsCategory = 'top' | 'president' | 'dept' | 'local';

export interface NewsCategoryMeta {
  key: NewsCategory;
  label: string;
  /** 左栏栏目树下方的说明文字 */
  desc: string;
}

/** 子栏目顺序即左栏栏目树的顺序 */
export const NEWS_CATEGORIES: NewsCategoryMeta[] = [
  { key: 'top', label: '头条新闻', desc: '本站编辑部认为您最需要知道的事。' },
  { key: 'president', label: '总统活动', desc: '总统到场的那一天，是当地服务水平的峰值。' },
  { key: 'dept', label: '部委动态', desc: '关于表格、时限与维护窗口的最新精神。' },
  { key: 'local', label: '地方传真', desc: '来自各州、县、市服务窗口的一线报道。' },
];

/** 判断任意字符串是否为合法子栏目 key */
export function isNewsCategory(v: string | undefined): v is NewsCategory {
  return v === 'top' || v === 'president' || v === 'dept' || v === 'local';
}

/** 取子栏目的中文名，未知值回落为「要闻动态」 */
export function categoryLabel(key: string): string {
  return NEWS_CATEGORIES.find((c) => c.key === key)?.label ?? '要闻动态';
}

