/* ================= 4. 辅助函数 ================= */

/** 全部可下载条目（表格 + 指南 + 客户端统一检索用） */
const ALL_ITEMS: DownloadItem[] = [...DOWNLOADS, ...GUIDES];

/** 按 id 查表格或指南 */
export function findDownload(id: string): DownloadItem | undefined {
  return ALL_ITEMS.find((d) => d.id === id);
}

/** 按格式筛选表格（大小写不敏感）；传入空串返回全部 */
export function downloadsByFormat(format: string): DownloadItem[] {
  if (!format) return DOWNLOADS;
  const f = format.toUpperCase();
  return DOWNLOADS.filter((d) => d.format.toUpperCase() === f);
}

/** 下载量前 n 名（按 downloads 降序，不改动原数组顺序） */
export function topDownloads(n: number): DownloadItem[] {
  return [...DOWNLOADS].sort((a, b) => b.downloads - a.downloads).slice(0, Math.max(0, n));
}

/** 按 id 查办事指南 */
export function findGuide(id: string): DownloadItem | undefined {
  return GUIDES.find((g) => g.id === id);
}

/** 按 id 查客户端 */
export function findApp(id: string): AppItem | undefined {
  return APPS.find((a) => a.id === id);
}

