/**
 * 总统讲话 / 每日推文 / 记者会实录数据
 *
 * I. 内容说明
 *
 * 1. SPEECHES        —— 重要讲话，26 篇，每篇含完整讲话全文（6-14 段）
 * 2. TWEETS          —— 每日推文，44 条，推特信息流的排版数据源
 * 3. PRESS_BRIEFINGS —— 记者会实录，12 场，问答体
 *
 * II. 写作约定
 *
 * 1. 语气一律使用标准公文语气，荒谬藏在具体数字与时限里。
 * 2. 全文不使用感叹号（这是全站硬性规则），不使用网络流行语。
 * 3. 所有人物均为虚构讽刺角色，统一以「总统」「发言人」「副总统」等
 *    角色称谓出现，不指向任何真实个体。
 *
 * III. 数据形态
 *
 * 讲话与记者会实录沿用共享的 Article 结构（type.ts），并各自扩展
 * 少量本模块专用字段；推文因为要还原信息流排版，单独定义 Tweet。
 *
 * @module data/speeches
 * @author zexuan.peng <pengzexuan2001@gmail.com>
 * @created 2026-09-30
 */
import type { Article } from './types';

/* ================= 类型 ================= */

/** 重要讲话（Article 扩展：主题、场合、要点摘录） */
export interface Speech extends Article {
  /** 主题分类，见 SPEECH_TOPICS */
  topic: string;
  /** 讲话场合 */
  occasion: string;
  /** 讲话地点 */
  place: string;
  /** 讲话要点摘录（详情页文末展示 3-5 条） */
  points: string[];
  /** 记录整理单位 */
  recorder?: string;
}

/** 每日推文（推特信息流） */
export interface Tweet {
  id: string;
  /** 发布时间，如「3 月 14 日 06:41」 */
  time: string;
  /** 正文，不超过 280 字符 */
  text: string;
  /** 点赞数（虚构，通常离谱地大） */
  likes: number;
  /** 转发数（虚构） */
  retweets: number;
  /** 评论数（虚构，通常离谱地小） */
  replies: number;
  /** 发布者角色称谓 */
  author: string;
  /** 账号名（虚构） */
  handle: string;
  /** 方形头像框内显示的字 */
  avatar: string;
  /** 头像配色 */
  tone: 'red' | 'navy' | 'gold';
  /** 小字备注（古早网站式的系统提示） */
  note?: string;
  /** 是否置顶 */
  pinned?: boolean;
}

/** 记者会实录（Article 扩展：场次编号、地点、出席人） */
export interface PressBriefing extends Article {
  /** 主题分类，与讲话主题共用一套取值 */
  topic: string;
  /** 场次编号 */
  pressNo: string;
  /** 举行地点 */
  place: string;
  /** 主席台人员（角色称谓） */
  speakers: string[];
}

