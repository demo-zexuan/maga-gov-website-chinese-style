/** 全部新闻，按日期倒序 */
export const NEWS: Article[] = [
  ...NEWS_TOP,
  ...NEWS_PRESIDENT,
  ...NEWS_DEPT,
  ...NEWS_LOCAL,
].sort(byDateDesc);

/* ================= 查询辅助函数 ================= */

/**
 * 按 id 精确查找一条新闻
 *
 * @param id - 形如 `nws-001` 的新闻编号
 * @returns 命中的稿件的；未命中返回 undefined，由详情页渲染 404 区块
 */
export function findNews(id: string): Article | undefined {
  return NEWS.find((n) => n.id === id);
}

/** 取某个子栏目的全部稿件，日期倒序 */
export function newsByCategory(cat: string): Article[] {
  return NEWS.filter((n) => n.category === cat);
}

/**
 * 取 n 条要闻
 *
 * I. 排序规则
 *
 * 1. 置顶稿件优先。
 * 2. 同级按阅读量倒序。
 * 3. 阅读量相同时按发布日期倒序。
 *
 * @param n - 需要的条数，默认 8
 */
export function topNews(n = 8): Article[] {
  return [...NEWS]
    .sort((a, b) => {
      if (!!b.top !== !!a.top) return b.top ? 1 : -1;
      if ((b.views ?? 0) !== (a.views ?? 0)) return (b.views ?? 0) - (a.views ?? 0);
      return byDateDesc(a, b);
    })
    .slice(0, n);
}

/**
 * 关键词检索
 *
 * 标题命中权重最高，其次为摘要、来源、文号与正文段落数；
 * 结果按相关度倒序，相关度相同时按日期倒序。
 */
export function searchNews(q: string): Article[] {
  const key = q.trim().toLowerCase();
  if (!key) return [];

  const scoreOf = (a: Article): number => {
    let score = 0;
    if (a.title.toLowerCase().includes(key)) score += 10;
    if ((a.summary ?? '').toLowerCase().includes(key)) score += 4;
    if (a.source.toLowerCase().includes(key)) score += 3;
    if ((a.docNo ?? '').toLowerCase().includes(key)) score += 2;
    const hitParas = a.body.filter((p) => p.toLowerCase().includes(key)).length;
    score += Math.min(hitParas, 3);
    return score;
  };

  return NEWS.filter((a) => scoreOf(a) > 0).sort(
    (a, b) => scoreOf(b) - scoreOf(a) || byDateDesc(a, b)
  );
}

/**
 * 相关阅读
 *
 * 同栏目优先，其次为标题关键词重合度高的稿件，永远排除自身。
 */
export function relatedNews(id: string, n = 6): Article[] {
  const self = findNews(id);
  if (!self) return [];

  // 以 2 字为一组切词，用于粗略估算标题重合度
  const grams = (s: string): string[] => {
    const out: string[] = [];
    for (let i = 0; i < s.length - 1; i += 2) out.push(s.slice(i, i + 2));
    return out;
  };
  const selfGrams = new Set(grams(self.title));

  const overlap = (a: Article): number =>
    grams(a.title).filter((g) => selfGrams.has(g)).length;

  return NEWS.filter((x) => x.id !== id)
    .sort((a, b) => {
      const catDiff = Number(b.category === self.category) - Number(a.category === self.category);
      if (catDiff !== 0) return catDiff;
      const ov = overlap(b) - overlap(a);
      if (ov !== 0) return ov;
      return byDateDesc(a, b);
    })
    .slice(0, n);
}

/**
 * 同一栏目内的上一篇 / 下一篇
 *
 * 上一篇指列表中更靠前（更新）的一条，下一篇指更靠后（更早）的一条，
 * 与古早政务网站「上一篇 / 下一篇」的导航习惯一致。
 */
export function adjacentNews(id: string): { prev?: Article; next?: Article } {
  const idx = NEWS.findIndex((n) => n.id === id);
  if (idx < 0) return {};
  return { prev: NEWS[idx - 1], next: NEWS[idx + 1] };
}
