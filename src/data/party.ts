/**
 * 把路由参数规范化为合法 tab
 *
 * @param tab - `/party/:tab` 中的 tab 参数
 * @returns 合法的 tab 键；无法识别时返回 'news'
 */
export function normalizePartyTab(tab?: string): PartyTabKey {
  const hit = PARTY_TAB_KEYS.find((k) => k === tab);
  return hit ?? 'news';
}

/**
 * 取某个栏目下的文章
 *
 * @param tab - 栏目标识（未识别时回退到党建要闻）
 * @returns 该栏目的全部文章，按数据原顺序（日期由新到旧）
 */
export function partyArticlesByTab(tab?: string): Article[] {
  const key = normalizePartyTab(tab);
  return PARTY_TABS.find((t) => t.key === key)?.articles ?? PARTY_NEWS;
}

/**
 * 按 id 查文章
 *
 * @param id - 文章 id，形如 pty-n001 / pty-s001 / pty-m001 / pty-c001
 * @returns 命中文章；未命中返回 undefined
 */
export function findPartyArticle(id: string): Article | undefined {
  return [...PARTY_NEWS, ...STUDY_MATERIALS, ...MODELS, ...CLEAN_GOV].find((a) => a.id === id);
}

