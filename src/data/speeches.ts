/** 最新的 n 篇讲话（列表按日期倒序） */
export function latestSpeeches(): Speech[] {
  return SPEECHES.slice().sort((a, b) => (a.date < b.date ? 1 : -1));
}

/**
 * 相关讲话：同主题优先，其次按日期就近补齐
 *
 * @param speech - 当前讲话
 * @param n      - 返回条数
 */
export function relatedSpeeches(speech: Speech, n = 5): Speech[] {
  const sameTopic = SPEECHES.filter((s) => s.id !== speech.id && s.topic === speech.topic);
  const others = SPEECHES.filter((s) => s.id !== speech.id && s.topic !== speech.topic).sort(
    (a, b) => (a.date < b.date ? 1 : -1)
  );
  return sameTopic.concat(others).slice(0, n);
}

/**
 * 讲话要点摘录（右侧栏「讲话要点」）
 *
 * 从最新的若干篇讲话中各取第一条要点，拼成一份"金句墙"。
 *
 * @param n - 条数
 * @returns { text, from, speechId } 数组
 */
export function featuredPoints(n = 6): { text: string; from: string; speechId: string }[] {
  return latestSpeeches()
    .slice(0, n)
    .map((s) => ({ text: s.points[0] ?? s.summary ?? s.title, from: s.title, speechId: s.id }));
}

/** 全站推文互动数据汇总（右栏数据看板用） */
export function tweetTotals(): { likes: number; retweets: number; replies: number; count: number } {
  return TWEETS.reduce(
    (acc, t) => ({
      likes: acc.likes + t.likes,
      retweets: acc.retweets + t.retweets,
      replies: acc.replies + t.replies,
      count: acc.count + 1,
    }),
    { likes: 0, retweets: 0, replies: 0, count: 0 }
  );
}

/**
 * 解析记者会实录的问答段落
 *
 * 数据里的每一段以「发言人：」「记者：」「主持人：」等角色前缀开头，
 * 这里把前缀单独拆出来，交给页面渲染成不同的样式。
 *
 * 之所以用白名单匹配而不是简单找冒号，是因为实录里还有「（演示环节：…）」
 * 这类没有角色的段落，属于场景说明，不能当作发言。
 *
 * @param body - 实录正文段落
 * @returns { speaker, text } 数组；无前缀的段落 speaker 为空字符串
 */
const QA_SPEAKER_RE = /^(记者|发言人|主持人|总统|副总统|局长|部长|主任)(（[^）]{1,6}）)?$/;

export function parseQa(body: string[]): { speaker: string; text: string }[] {
  return body.map((line) => {
    const idx = line.indexOf('：');
    if (idx > 0) {
      const head = line.slice(0, idx);
      if (QA_SPEAKER_RE.test(head)) {
        return { speaker: head, text: line.slice(idx + 1) };
      }
    }
    return { speaker: '', text: line };
  });
}
